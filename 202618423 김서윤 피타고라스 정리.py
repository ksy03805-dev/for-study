#변수 선언 및 입력 부분#
x1 = float(input("첫 번째 점의 x1 좌표를 입력하세요: "))
y1 = float(input("두 번째 점의 y1 좌표를 입력하세요: "))
x2 = float(input("세 번째 점의 x2 좌표를 입력하세요: "))
y2 = float(input("네 번째 점의 y2 좌표를 입력하세요: "))

#피타고라스 정리를 이용해서 거리를 구하기#
distance = ((x2-x1)**2 + (y2-y1)**2)**0.5

#출력하기#
print("\n점 ({0}, {1})과 점 ({2}, {3}) 사이의 거리: {4:.2f}".format(x1, y1, x2, y2, distance))
